/** Outils internes du CLI, sans travail à montrer (ToolSearch charge la description d'un outil MCP). */
const HIDDEN = new Set(["ToolSearch"]);

/**
 * « mcp__kopilia__ask_agent » -> « Agent dépêché » ; un outil inconnu garde son
 * nom court ; un outil interne du CLI n'est pas une étape (undefined).
 */
export function stepLabel(tool: string): string | undefined {
  if (HIDDEN.has(tool)) return undefined;
  const short = tool.startsWith("mcp__") ? tool.split("__").slice(2).join("__") : tool;
  return STEP_LABELS[short] ?? short.replace(/_/g, " ");
}
